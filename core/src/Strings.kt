    fun resolve(saved: String?, systemLang: String?): String {
        if (saved != null && saved in LANGS) return saved
        val s = (systemLang ?: "").lowercase()
        return when {
            s.startsWith("ja") -> "ja"
            s.startsWith("fr") -> "fr"
            s.startsWith("de") -> "de"
            s.startsWith("it") -> "it"
            s.startsWith("es") -> "es"
            s.startsWith("ru") -> "ru"
            s.startsWith("pt") -> "pt"
            s.startsWith("pl") -> "pl"
            s.startsWith("ko") -> "ko"
            s.startsWith("zh") -> if (s.contains("hant") || s.contains("tw") || s.contains("hk")) "zh-Hant" else "zh-Hans"
            else -> "en"
        }
    }

    var lang: String = "ja"
